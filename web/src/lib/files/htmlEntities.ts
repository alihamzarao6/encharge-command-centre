const REPLACEMENT = 0xfffd;

function fromNumber(code: number): string {
  if (!Number.isInteger(code) || code <= 0 || code > 0x10ffff) {
    return String.fromCodePoint(REPLACEMENT);
  }
  // A surrogate on its own is not a character.
  if (code >= 0xd800 && code <= 0xdfff) return String.fromCodePoint(REPLACEMENT);
  const mapped = Object.hasOwn(C1_AS_WINDOWS_1252, code) ? C1_AS_WINDOWS_1252[code] : undefined;
  return String.fromCodePoint(mapped ?? code);
}

const REFERENCE = /&(?:#x([0-9a-f]{1,8})|#(\d{1,8})|([a-z][a-z0-9]{1,31}));/gi;

/** Text with its character references resolved. Unknown names are left as written. */
export function decodeEntities(text: string): string {
  if (!text.includes('&')) return text;
  return text.replace(
    REFERENCE,
    (whole: string, hex?: string, decimal?: string, name?: string): string => {
      if (hex !== undefined) return fromNumber(Number.parseInt(hex, 16));
      if (decimal !== undefined) return fromNumber(Number.parseInt(decimal, 10));
      if (name !== undefined && Object.hasOwn(NAMED, name)) {
        const code = NAMED[name];
        if (code !== undefined) return String.fromCodePoint(code);
      }
      return whole;
    },
  );
}
